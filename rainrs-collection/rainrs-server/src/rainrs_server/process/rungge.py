#: Identifier stored with every derived key.
ALGORITHM = "rk4-vandepol-sha256"

#: Integration defaults. The step count is large enough for the
#: trajectory to explore the attractor but still runs in milliseconds.
DEFAULT_STEP_SIZE = 0.01
DEFAULT_STEPS = 4000
DEFAULT_SAMPLE_EVERY = 10

#: Domain separation labels, so that master and slave material can
#: never collide even when they are derived from identical parameters.
MASTER_LABEL = b"rainrs/v1/master"
SLAVE_LABEL = b"rainrs/v1/slave"

Vector = tuple[float, ...]
Derivative = Callable[[float, Vector], Vector]

BINDING_HMAC = "hmac"
BINDING_XOR = "xor"
ALLOWED_BINDINGS = (BINDING_HMAC, BINDING_XOR)


def utc_now_iso() -> str:
    """Return the current UTC time as an ISO 8601 string."""
    return datetime.now(UTC).isoformat(timespec="seconds")


# ---------------------------------------------------------------------------
# Runge-Kutta core
# ---------------------------------------------------------------------------
def rk4_step(derivative: Derivative, t: float, state: Vector, dt: float) -> Vector:
    """Advance ``state`` by one classical RK4 step of size ``dt``.

    Args:
        derivative: Right-hand side of the ODE system.
        t: Current time.
        state: Current state vector.
        dt: Step size.

    Returns:
        The state at ``t + dt``.
    """
    k1 = derivative(t, state)
    half = tuple(y + 0.5 * dt * k for y, k in zip(state, k1, strict=True))
    k2 = derivative(t + 0.5 * dt, half)
    half = tuple(y + 0.5 * dt * k for y, k in zip(state, k2, strict=True))
    k3 = derivative(t + 0.5 * dt, half)
    full = tuple(y + dt * k for y, k in zip(state, k3, strict=True))
    k4 = derivative(t + dt, full)
    return tuple(
        y + (dt / 6.0) * (a + 2.0 * b + 2.0 * c + d)
        for y, a, b, c, d in zip(state, k1, k2, k3, k4, strict=True)
    )


def rk4_integrate(
    derivative: Derivative,
    initial_state: Vector,
    *,
    dt: float = DEFAULT_STEP_SIZE,
    steps: int = DEFAULT_STEPS,
    sample_every: int = DEFAULT_SAMPLE_EVERY,
) -> list[Vector]:
    """Integrate ``derivative`` with RK4 and return the sampled trajectory.

    Args:
        derivative: Right-hand side of the ODE system.
        initial_state: State at ``t = 0``.
        dt: Step size.
        steps: Number of integration steps.
        sample_every: Keep every ``sample_every``-th state.

    Returns:
        The sampled states, starting with the initial state.
    """
    if dt <= 0:
        raise ValueError(f"step size must be positive, got {dt}")
    if steps <= 0:
        raise ValueError(f"number of steps must be positive, got {steps}")
    if sample_every <= 0:
        raise ValueError(f"sample_every must be positive, got {sample_every}")

    state = tuple(initial_state)
    time = 0.0
    samples = [state]
    for step in range(1, steps + 1):
        state = rk4_step(derivative, time, state, dt)
        time += dt
        if step % sample_every == 0:
            samples.append(state)
    return samples


# ---------------------------------------------------------------------------
# ODE system
# ---------------------------------------------------------------------------
@dataclass(frozen=True, slots=True)
class RippleWaveParameters:
    """Parameters of the coupled oscillator system.

    Attributes:
        mu: Nonlinearity (van der Pol damping) of both oscillators.
        coupling: Coupling strength between the two oscillators.
        forcing: Amplitude of the periodic forcing term.
        phase: Phase of the forcing term in radians.
    """

    mu: float
    coupling: float
    forcing: float
    phase: float

    def to_dict(self) -> dict[str, float]:
        """Return the parameters as a plain dictionary."""
        return {
            "mu": self.mu,
            "coupling": self.coupling,
            "forcing": self.forcing,
            "phase": self.phase,
        }


class RippleWaveSystem:
    """Two coupled van der Pol oscillators driven by a ripple geometry.

    The state is ``(x1, x2, y1, y2)``: position and velocity of the
    horizontal and the vertical oscillator. The equations are

    .. code-block:: text

        dx1/dt = x2
        dx2/dt = mu * (1 - x1^2) * x2 - coupling * (x1 - y1) + forcing * cos(phase)
        dy1/dt = y2
        dy2/dt = mu * (1 - y1^2) * y2 - coupling * (y1 - x1) + forcing * sin(phase)
    """

    def __init__(self, parameters: RippleWaveParameters) -> None:
        self.parameters = parameters

    def __call__(self, t: float, state: Vector) -> Vector:
        """Evaluate the right-hand side at ``(t, state)``."""
        x1, x2, y1, y2 = state
        p = self.parameters
        dx1 = x2
        dx2 = (
            p.mu * (1.0 - x1 * x1) * x2
            - p.coupling * (x1 - y1)
            + p.forcing * math.cos(p.phase)
        )
        dy1 = y2
        dy2 = (
            p.mu * (1.0 - y1 * y1) * y2
            - p.coupling * (y1 - x1)
            + p.forcing * math.sin(p.phase)
        )
        return (dx1, dx2, dy1, dy2)


def _normalised_geometry(
    center_x: float, center_y: float, radius: float, width: int, height: int
) -> tuple[float, float, float]:
    """Return the normalised position ``(u, v)`` and radius ``rho``."""
    safe_width = max(int(width), 1)
    safe_height = max(int(height), 1)
    u = min(max(center_x / safe_width, 0.0), 1.0)
    v = min(max(center_y / safe_height, 0.0), 1.0)
    rho = min(max(radius / min(safe_width, safe_height), 0.0), 1.0)
    return u, v, rho


def parameters_for_ripple(
    ripple: RippleDetection, width: int, height: int
) -> RippleWaveParameters:
    """Return the ODE parameters derived from a single ripple."""
    u, v, rho = _normalised_geometry(
        ripple.center_x, ripple.center_y, ripple.radius, width, height
    )
    return RippleWaveParameters(
        mu=0.5 + 1.5 * rho,
        coupling=1.0 + 2.0 * u * v,
        forcing=1.0 + 4.0 * rho,
        phase=2.0 * math.pi * u,
    )


def parameters_for_master(
    attributes: RippleAttributes,
) -> RippleWaveParameters:
    """Return the ODE parameters derived from the averaged attributes.

    The averaged position and radius drive the oscillator, while the
    number of ripples scales the nonlinearity and the forcing.
    """
    u, v, rho = _normalised_geometry(
        attributes.mean_center_x,
        attributes.mean_center_y,
        attributes.mean_radius,
        attributes.image_width,
        attributes.image_height,
    )
    count = float(attributes.count)
    return RippleWaveParameters(
        mu=0.5 + 1.5 * rho + 0.05 * count,
        coupling=1.0 + 2.0 * u * v,
        forcing=1.0 + 4.0 * rho + 0.25 * count,
        phase=2.0 * math.pi * u,
    )


def _initial_state(u: float, v: float) -> Vector:
    """Return the initial state of the oscillator pair."""
    return (u, v, v, u)


def _trajectory_bytes(samples: Sequence[Vector]) -> bytes:
    """Serialise the sampled trajectory into a byte string."""
    chunks = []
    for sample in samples:
        chunks.append(struct.pack(f"<{len(sample)}d", *sample))
    return b"".join(chunks)


def _master_payload(attributes: RippleAttributes) -> bytes:
    """Canonical byte representation of the averaged attributes."""
    return struct.pack(
        "<4d",
        attributes.mean_center_x,
        attributes.mean_center_y,
        attributes.mean_radius,
        float(attributes.count),
    )


def _slave_payload(ripple: RippleDetection) -> bytes:
    """Canonical byte representation of a single ripple."""
    return struct.pack(
        "<5d",
        float(ripple.index),
        ripple.center_x,
        ripple.center_y,
        ripple.radius,
        ripple.confidence,
    )


# ---------------------------------------------------------------------------
# Key derivation
# ---------------------------------------------------------------------------
def derive_master_key(
    attributes: RippleAttributes,
    *,
    bits: int = 64,
    dt: float = DEFAULT_STEP_SIZE,
    steps: int = DEFAULT_STEPS,
    sample_every: int = DEFAULT_SAMPLE_EVERY,
) -> MasterKey:
    """Derive the master key of a capture from its averaged attributes.

    Args:
        attributes: The extracted ripple attributes of one capture.
        bits: Key size in bits (32 or 64).
        dt: Runge-Kutta step size.
        steps: Number of integration steps.
        sample_every: Sampling interval of the trajectory.

    Returns:
        The derived master key.

    Raises:
        ValueError: The capture contains no ripple, or the key size is
            not supported.
    """
    resolve_key_bits(bits)
    if not attributes.ripples:
        raise ValueError("a master key needs at least one ripple; the capture has none")

    parameters = parameters_for_master(attributes)
    u, v, _ = _normalised_geometry(
        attributes.mean_center_x,
        attributes.mean_center_y,
        attributes.mean_radius,
        attributes.image_width,
        attributes.image_height,
    )
    samples = rk4_integrate(
        RippleWaveSystem(parameters),
        _initial_state(u, v),
        dt=dt,
        steps=steps,
        sample_every=sample_every,
    )
    digest = hashlib.sha256(
        MASTER_LABEL + b"|" + _master_payload(attributes) + _trajectory_bytes(samples)
    ).digest()
    key = digest[: bits // 8].hex()

    return MasterKey(
        image_id=attributes.image_id or 0,
        key=key,
        bits=bits,
        algorithm=ALGORITHM,
        parameters={
            "mean_center_x": attributes.mean_center_x,
            "mean_center_y": attributes.mean_center_y,
            "mean_radius": attributes.mean_radius,
            "ripple_count": float(attributes.count),
            "image_width": float(attributes.image_width),
            "image_height": float(attributes.image_height),
            **{f"ode_{name}": value for name, value in parameters.to_dict().items()},
            "dt": dt,
            "steps": float(steps),
        },
        derived_at=utc_now_iso(),
    )


def derive_slave_keys(
    attributes: RippleAttributes,
    master_key: MasterKey,
    *,
    binding: str = BINDING_HMAC,
    dt: float = DEFAULT_STEP_SIZE,
    steps: int = DEFAULT_STEPS,
    sample_every: int = DEFAULT_SAMPLE_EVERY,
) -> list[SlaveKey]:
    """Derive one slave key per detected ripple.

    Every slave key is derived from the *individual* attributes of its
    ripple and is then bound to ``master_key``.

    Args:
        attributes: The extracted ripple attributes of one capture.
        master_key: The master key the slave keys belong to.
        binding: ``hmac`` (default) binds the slave key to the master
            key with HMAC-SHA256; ``xor`` applies a plain XOR instead.
        dt: Runge-Kutta step size.
        steps: Number of integration steps.
        sample_every: Sampling interval of the trajectory.

    Returns:
        One slave key per ripple, ordered by ripple index.
    """
    if binding not in ALLOWED_BINDINGS:
        raise ValueError(
            f"unsupported binding {binding!r}; expected one of {ALLOWED_BINDINGS}"
        )
    resolve_key_bits(master_key.bits)

    master_bytes = bytes.fromhex(master_key.key)
    slave_keys: list[SlaveKey] = []
    for ripple in attributes.ripples:
        parameters = parameters_for_ripple(
            ripple, attributes.image_width, attributes.image_height
        )
        u, v, _ = _normalised_geometry(
            ripple.center_x,
            ripple.center_y,
            ripple.radius,
            attributes.image_width,
            attributes.image_height,
        )
        samples = rk4_integrate(
            RippleWaveSystem(parameters),
            _initial_state(u, v),
            dt=dt,
            steps=steps,
            sample_every=sample_every,
        )
        digest = hashlib.sha256(
            SLAVE_LABEL + b"|" + _slave_payload(ripple) + _trajectory_bytes(samples)
        ).digest()
        raw = digest[: master_key.bits // 8]
        if binding == BINDING_HMAC:
            bound = hmac.new(master_bytes, raw, hashlib.sha256).digest()[
                : master_key.bits // 8
            ]
        else:
            bound = bytes(a ^ b for a, b in zip(raw, master_bytes, strict=True))
        slave_keys.append(
            SlaveKey(
                master_key_id=0,
                image_id=attributes.image_id or 0,
                ripple_index=ripple.index,
                key=bound.hex(),
                bits=master_key.bits,
                algorithm=f"{ALGORITHM}/{binding}",
                derived_at=utc_now_iso(),
            )
        )
    return slave_keys


class KeyDeriver:
    """Derive and store the research keys of the stored captures.

    Args:
        database_path: SQLite database holding the extracted attributes.
        bits: Key size in bits (32 or 64).
        binding: Binding between the slave keys and their master key.
        overwrite: Re-derive keys for captures that already have a
            master key. Off by default, so that a second run does not
            create duplicates.
    """

    def __init__(
        self,
        *,
        database_path: Path,
        bits: int = 64,
        binding: str = BINDING_HMAC,
        overwrite: bool = False,
        dt: float = DEFAULT_STEP_SIZE,
        steps: int = DEFAULT_STEPS,
        sample_every: int = DEFAULT_SAMPLE_EVERY,
    ) -> None:
        self._database_path = Path(database_path)
        self._bits = resolve_key_bits(bits)
        if binding not in ALLOWED_BINDINGS:
            raise ValueError(
                f"unsupported binding {binding!r}; expected one of {ALLOWED_BINDINGS}"
            )
        self._binding = binding
        self._overwrite = overwrite
        self._dt = dt
        self._steps = steps
        self._sample_every = sample_every

    def derive_for_image(self, image_id: int) -> tuple[MasterKey, list[SlaveKey]]:
        """Derive (and store) the keys of a single capture.

        Returns:
            The master key and its slave keys.

        Raises:
            LookupError: The capture is unknown.
            ValueError: The capture has no ripple.
        """
        with open_database(self._database_path) as connection:
            attributes = load_image(connection, image_id)
            if attributes is None:
                raise LookupError(f"unknown image id: {image_id}")
            if not attributes.ripples:
                raise ValueError(f"image {image_id} has no ripple attributes")

            existing = find_master_key_for_image(connection, image_id)
            if existing is not None and not self._overwrite:
                logger.info("image %d already has a master key - skipped", image_id)
                return existing, []
            if existing is not None:
                delete_master_key_for_image(connection, image_id)

            master_key = derive_master_key(
                attributes,
                bits=self._bits,
                dt=self._dt,
                steps=self._steps,
                sample_every=self._sample_every,
            )
            master_key = MasterKey(
                image_id=image_id,
                key=master_key.key,
                bits=master_key.bits,
                algorithm=master_key.algorithm,
                parameters=master_key.parameters,
                derived_at=master_key.derived_at,
            )
            master_key_id = store_master_key(connection, master_key)

            slave_keys = derive_slave_keys(
                attributes,
                master_key,
                binding=self._binding,
                dt=self._dt,
                steps=self._steps,
                sample_every=self._sample_every,
            )
            stored_slaves = []
            for slave in slave_keys:
                stored = SlaveKey(
                    master_key_id=master_key_id,
                    image_id=image_id,
                    ripple_index=slave.ripple_index,
                    key=slave.key,
                    bits=slave.bits,
                    algorithm=slave.algorithm,
                    derived_at=slave.derived_at,
                )
                store_slave_key(connection, stored)
                stored_slaves.append(stored)

            logger.info(
                "derived 1 master key and %d slave key(s) for image %d",
                len(stored_slaves),
                image_id,
            )
            dev_print(
                "image %d: master=%s (%d slave keys)",
                image_id,
                master_key.key,
                len(stored_slaves),
            )
            return master_key, stored_slaves

    def derive_for_all(self, image_ids: Sequence[int] | None = None) -> list[MasterKey]:
        """Derive the keys of every stored capture.

        Args:
            image_ids: Restrict the derivation to these captures. By
                default every capture in the database is processed.

        Returns:
            The master keys that were derived.
        """
        with open_database(self._database_path) as connection:
            targets = (
                list(image_ids) if image_ids is not None else list_image_ids(connection)
            )

        derived: list[MasterKey] = []
        for image_id in targets:
            try:
                master_key, _ = self.derive_for_image(image_id)
            except LookupError:
                logger.warning("image %d is unknown - skipped", image_id)
                continue
            except ValueError as exc:
                logger.warning("image %d skipped: %s", image_id, exc)
                continue
            derived.append(master_key)
        return derived

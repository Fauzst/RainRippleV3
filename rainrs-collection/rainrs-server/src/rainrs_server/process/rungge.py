"""Runge–Kutta key derivation from rain-ripple attributes.

The derivation turns the geometry of the detected ripples into
experimental key material. Two levels are produced for every capture:

* a **master key**, derived from the *averaged* attributes of the image
  (mean centre position, mean radius and the number of ripples);
* one **slave key** per detected ripple, derived from the *individual*
  attributes of that ripple and bound to the master key.

Inputs
------
* :class:`~rainrs_server.models.RippleAttributes` for one capture —
  typically loaded from the ``images`` table that
  :mod:`rainrs_server.process.image_read` writes.

Outputs
-------
* :class:`~rainrs_server.models.MasterKey` and a list of
  :class:`~rainrs_server.models.SlaveKey` objects.
* Rows in the ``master_keys`` and ``slave_keys`` tables of the SQLite
  database; every slave key references the master key it belongs to.

Method
------
A four dimensional system of ordinary differential equations — two
coupled van der Pol oscillators — is integrated with the classical
fourth order Runge–Kutta method (RK4). The geometry of a ripple sets
the oscillator parameters (nonlinearity, coupling, forcing and phase);
the trajectory of the integration is then condensed with SHA-256 into
the key material.

Security note
-------------
The output is **experimental research material**, not a production
cryptographic key:

* the derivation is fully deterministic — the same capture always
  produces the same key, so the "randomness" of the artifact comes from
  the physical capture and not from the algorithm;
* the resulting 32/64 bit values are far too short for cryptographic
  use and have not been evaluated with a statistical test suite yet;
* the slave keys are bound to their master key with HMAC-SHA256 (a
  standard primitive) instead of a plain XOR. XOR would let two equal
  inputs cancel out and would not separate the child key from the
  parent; the XOR variant stays available for comparison.

Production encryption must use established cryptographic libraries,
approved algorithms and keys generated by a CSPRNG.
"""

